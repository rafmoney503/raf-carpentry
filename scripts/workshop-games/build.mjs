#!/usr/bin/env node
/* Workshop Games: turns the screens designed on the 'Workshop Games mockups' design canvas (the .dc.html files here,
   one per screen, copied from the canvas and made ready for the app) into src/lib/workshop-games/boards.generated.js,
   which src/app/tools/games/app/games-app.tsx draws with src/lib/workshop-tools/dc-runtime.tsx (the same runtime as
   Workshop Tools).

   Every screen was designed at 390 x 844. How each one meets a real phone:
   - fill: the screen takes the whole height and width (up to 520 wide; on phones narrower than 390 it is laid out at
     390 and scaled down to fit); the game's stage inside scales itself to the room left (makeFit in the screen's
     logic), so a short Safari screen still plays at full width.
   - contain: the whole 390 x 844 screen is scaled to fit (Sheet Saver, whose parts are dragged across all of it).
   - scroll: the screen keeps its size (scaled down only on phones narrower than 390) and the page scrolls (home and
     the level screens).
   The app page sets --fit, --fs and --h on the box round each screen.

   After changing a screen: edit the .dc.html here (or copy it from the canvas and redo the app changes), then
   `node scripts/workshop-games/build.mjs`. No dependencies. */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { splitDc, parse, convert, count, resetCount } from '../dc/convert.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const out = join(root, 'src/lib/workshop-games/boards.generated.js');

export const SCREENS = {
  home: { file: 'home.dc.html', mode: 'scroll' },
  stack: { file: 'stack.dc.html', mode: 'fill' },
  'stack/levels': { file: 'stack-levels.dc.html', mode: 'scroll' },
  nail: { file: 'nail.dc.html', mode: 'fill' },
  'nail/levels': { file: 'nail-levels.dc.html', mode: 'scroll' },
  measure: { file: 'measure.dc.html', mode: 'fill' },
  'measure/packs': { file: 'measure-packs.dc.html', mode: 'scroll' },
  sheet: { file: 'sheet.dc.html', mode: 'contain' },
  'sheet/boards': { file: 'sheet-boards.dc.html', mode: 'scroll' },
  level: { file: 'level.dc.html', mode: 'fill' },
  'level/boards': { file: 'level-boards.dc.html', mode: 'scroll' },
};

const MODE_CSS = {
  // under 390 wide (--fs below 1) the screen is laid out at 390 and scaled down, so its header and buttons stay as designed
  fill: ':host{position:relative;height:100%;overflow:hidden}.dc-root{width:calc(100% / var(--fs,1)) !important;height:calc(100% / var(--fs,1)) !important;max-width:520px;margin:0 auto;transform:scale(var(--fs,1));transform-origin:top left}',
  contain: ':host{position:relative;height:100%;overflow:hidden}.dc-root{position:absolute !important;left:50%;top:50%;transform:translate(-50%,-50%) scale(var(--fit,1));transform-origin:center center}',
  scroll: ':host{position:relative;height:var(--h,844px);overflow:hidden}.dc-root{position:absolute !important;left:50%;top:0;transform:translateX(-50%) scale(var(--fit,1));transform-origin:top center}',
};

let total = 0;
const parts = [];
for (const [name, { file, mode }] of Object.entries(SCREENS)) {
  resetCount();
  const { css, template, logic } = splitDc(readFileSync(join(here, file), 'utf8'));
  // canvas-only rules (the canvas page's body) go; links to the canvas's other boards were made app addresses
  const tree = convert(parse(template));
  if (/\.dc\.html/.test(JSON.stringify(tree))) throw new Error(`${file} still links to a .dc.html board`);
  const first = tree.find((n) => n && typeof n === 'object' && n.t);
  if (!first) throw new Error(`${file} has no screen`);
  first.a = first.a || {};
  first.a.className = ((first.a.className || '') + ' dc-root').trim();
  const allCss = MODE_CSS[mode] + '\n' + css.replace(/body\{margin:0\}\s*/g, '');
  parts.push(`  ${JSON.stringify(name)}: {
    mode: ${JSON.stringify(mode)},
    CSS: ${JSON.stringify(allCss)},
    TEMPLATE: ${JSON.stringify(tree)},
    defineComponent(DCLogic) {
${logic}
      return Component;
    },
  }`);
  total += count.el;
  console.log(`${name.padEnd(14)} ${mode.padEnd(8)} ${count.el} elements, ${count.ifs} sc-if, ${count.fors} sc-for, ${count.holes} holes`);
}

const code = `/* eslint-disable */
// @ts-nocheck
/* GENERATED by scripts/workshop-games/build.mjs from scripts/workshop-games/*.dc.html (the 'Workshop Games mockups'
   design canvas, made ready for the app). Do not edit: change the .dc.html files and run the script. */

export const BOARDS = {
${parts.join(',\n')}
};
`;
writeFileSync(out, code);
console.log(`Wrote ${out}: ${total} elements, ${(code.length / 1024).toFixed(0)} KB`);
